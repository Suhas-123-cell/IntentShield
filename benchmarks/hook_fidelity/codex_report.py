#!/usr/bin/env python3
"""Tables of the Codex lane, generated from the committed rows (no narrative, no hand-copied numbers).

    codex_report.py runs.jsonl by-version.md          # outcome per release x reply, one table per (mode, kind, state)
    codex_report.py --pilot pilot/runs.jsonl pilot-bundled/runs.jsonl pilot.md   # tool surface: stub slug and a bundled slug

Cell text is ``OUTCOME k/n`` of the valid rows of the cell; several outcomes are joined by `` | ``; ``(h)`` marks a cell whose
hook was observed in every valid run, ``(no h)`` one where it was observed in none, ``(h partial)`` in some; no mark for R0
(no hook). INVALID rows are not counted in n; the number of INVALID rows of the cell is added as ``+Ni``. Rates are k/n and
nothing is rounded.
"""
from __future__ import annotations

import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

REPLY_ORDER = ["R0", "R1", "R2", "R3", "R4", "R5", "R6", "R7", "R8", "R9", "R10b", "R11", "R15", "R16"]
NAMES = {"R0": "no hook", "R1": "neutral {}", "R2": "allow", "R3": "ask", "R4": "deny+reason", "R5": "empty, exit 0",
         "R6": "malformed JSON", "R7": "exit 2 + stderr", "R8": "exit 1", "R9": "timeout", "R10b": "dead interpreter",
         "R11": "exit 2, empty stderr", "R15": "exit 126", "R16": "exit 127"}


def _vkey(version: str) -> tuple:
    return tuple(int(p) for p in version.split("."))


def cell_text(rows: list[dict]) -> str:
    valid = [r for r in rows if r["outcome"] != "INVALID"]
    invalid = len(rows) - len(valid)
    if not valid:
        return f"INVALID x{invalid}"
    counts = Counter(r["outcome"] for r in valid)
    text = " | ".join(f"{o} {k}/{len(valid)}" for o, k in sorted(counts.items(), key=lambda kv: -kv[1]))
    hooks = [r["hook_invoked"] for r in valid if r["hook_invoked"] is not None]
    if hooks:
        text += " (h)" if all(hooks) else " (no h)" if not any(hooks) else " (h partial)"
    return text + (f" +{invalid}i" if invalid else "")


def by_version(rows: list[dict]) -> str:
    groups: dict[tuple, dict[tuple, list[dict]]] = defaultdict(lambda: defaultdict(list))
    for r in rows:
        groups[(r["mode"], r["kind"], r["state"])][(r["reply"], r["version"])].append(r)
    out = ["# Codex outcome per release and reply (generated by benchmarks/hook_fidelity/codex_report.py)", "",
           "Arm S (stub model endpoint, fake key, isolated HOME). Cell = outcome k/n over valid runs; (h) = hook invoked in "
           "every valid run; (no h) = in none; +Ni = N INVALID rows. Source: runs.jsonl next to this file.", ""]
    for (mode, kind, state), cells in sorted(groups.items()):
        versions = sorted({v for _, v in cells}, key=_vkey)
        replies = [r for r in REPLY_ORDER if any(k[0] == r for k in cells)]
        out += [f"## mode {mode}, tool {kind}, hook state {state}", "",
                "| reply | " + " | ".join(versions) + " |", "|---|" + "---|" * len(versions)]
        for reply in replies:
            row = [cell_text(cells[(reply, v)]) if (reply, v) in cells else "" for v in versions]
            out.append(f"| {reply} {NAMES.get(reply, '')} | " + " | ".join(row) + " |")
        out.append("")
    return "\n".join(out)


def pilot_tables(pilot_rows: list[dict], bundled_rows: list[dict]) -> str:
    def surface(rows: list[dict]) -> tuple[str, list[str]]:
        for r in rows:
            offered = r.get("stub", {}).get("offered_tools")
            if offered:
                return r["model"], offered
        return "", []

    stub_slug, stub_tools = surface(pilot_rows)
    bundled_slug, bundled_tools = surface(bundled_rows)
    out = ["# Codex stub-arm pilot: tool surface and pass criteria (generated)", "",
           f"Codex {pilot_rows[0]['version'] if pilot_rows else '?'}: what each model slug exposes to the model (the stub's "
           "`offered_tools` of the first request that carried the scripted call).", "",
           f"| tool | {stub_slug} (unknown slug, fallback metadata) | {bundled_slug} (bundled slug) |", "|---|---|---|"]
    for tool in sorted(set(stub_tools) | set(bundled_tools)):
        out.append(f"| {tool} | {'offered' if tool in stub_tools else '-'} | {'offered' if tool in bundled_tools else '-'} |")
    out += ["", "## Pass criteria per pilot row", "",
            "| slug | kind | reply | outcome | hook invoked | stub decisions | scripted tool offered | call_index | egress |",
            "|---|---|---|---|---|---|---|---|---|"]
    for r in [*pilot_rows, *bundled_rows]:
        s = r["stub"]
        out.append(f"| {r['model']} | {r['kind']} | {r['reply']} | {r['outcome']} | {r['hook_invoked']} | "
                   f"{', '.join(map(str, s['decisions']))} | {s['scripted_tool_offered']} | {s['call_index_max']} | "
                   f"{len(r.get('egress_attempts', []))} |")
    out += ["", "## What the harness sent back after the call (the stub's `tool_results`, paths scrubbed)", ""]
    seen = set()
    for r in [*pilot_rows, *bundled_rows]:
        key = (r["model"], r["kind"], r["reply"])
        if key in seen:
            continue
        seen.add(key)
        text = r["stub"]["result_text"].replace("\n", " ").replace("|", "/")[:160]
        out.append(f"- {r['model']} {r['kind']} {r['reply']} {r['outcome']}: `{text}`")
    return "\n".join(out) + "\n"


def read(path: Path) -> list[dict]:
    return [json.loads(line) for line in path.read_text().splitlines() if line.strip()]


def main(argv: list[str]) -> int:
    if argv and argv[0] == "--pilot" and len(argv) == 4:
        Path(argv[3]).write_text(pilot_tables(read(Path(argv[1])), read(Path(argv[2]))))
        return 0
    if len(argv) == 2:
        Path(argv[1]).write_text(by_version(read(Path(argv[0]))) + "\n")
        return 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
